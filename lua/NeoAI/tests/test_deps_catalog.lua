--- 可选安全依赖目录/安装计划测试
local tests = require("NeoAI.tests")

tests.suite("deps_catalog", function(_, it)
  local catalog = require("NeoAI.utils.deps_catalog")

  it("列出依赖并返回状态", function(t)
    local list = catalog.list()
    t.true_(#list > 0)
    local st = catalog.status()
    t.eq(#list, #st)
    local has_bwrap = false
    for _, d in ipairs(st) do if d.id == "bubblewrap" then has_bwrap = true end end
    t.true_(has_bwrap)
  end)

  it("apt 计划是 argv 数组，不拼 shell；manual 依赖单独列出", function(t)
    catalog._set_pkg_manager("apt")
    local plan, err = catalog.plan({ "bubblewrap", "podman" })
    t.eq(nil, err)
    t.eq("apt", plan.pm)
    t.eq("apt", plan.argv[1])
    t.eq("install", plan.argv[2])
    t.true_(vim.tbl_contains(plan.argv, "bubblewrap"))
    t.true_(vim.tbl_contains(plan.argv, "podman"))
    t.matches("bubblewrap", catalog.command_string(plan))
    local only, err2 = catalog.plan({ "kata" })
    t.eq(nil, only)
    t.matches("MANUAL_ONLY", err2)
    catalog.reset()
  end)

  it("未知依赖/无包管理器返回错误", function(t)
    catalog._set_pkg_manager("generic")
    local p, e = catalog.plan({ "bubblewrap" })
    t.eq(nil, p)
    t.eq("NO_PACKAGE_MANAGER", e)
    catalog._set_pkg_manager("apt")
    local p2, e2 = catalog.plan({ "nope" })
    t.eq(nil, p2)
    t.eq("UNKNOWN_DEP:nope", e2)
    catalog.reset()
  end)
end)
