-- ========== 私有函数 ==========

--- 区间表二分查找（区间按升序、互不重叠）
--- @param ranges table 区间数组 { {lo, hi}, ... }
--- @param cp number 码点
--- @return boolean
local function _in_ranges(ranges, cp)
  local lo, hi = 1, #ranges
  while lo <= hi do
    local mid = math.floor((lo + hi) / 2)
    local r = ranges[mid]
    if cp < r[1] then
      hi = mid - 1
    elseif cp > r[2] then
      lo = mid + 1
    else
      return true
    end
  end
  return false
end

--- 单码点显示宽度
--- @param cp number
--- @return number 0/1/2
local function _width(cp)
  if cp < 0x80 then
    -- ASCII（含控制字符，vim 均计 1 列；NUL 计 0）
    if cp == 0 then return 0 end
    return 1
  end
  -- 高频宽字符快速路径（CJK 汉字/假名/谚文/全角），避免二分查找
  if cp >= 0x4E00 and cp <= 0x9FFF then return 2 end
  -- 假名区间内 U+3099/U+309A 为组合浊点，需走组合表判 0
  if cp >= 0x3041 and cp <= 0x30FF and not (cp >= 0x3099 and cp <= 0x309A) then return 2 end
  if cp >= 0xAC00 and cp <= 0xD7A3 then return 2 end
  if cp >= 0xFF01 and cp <= 0xFF60 then return 2 end
  if cp >= 0x1F300 and cp <= 0x1FAFF then return 2 end
  if _in_ranges(WIDE, cp) then return 2 end
  if _in_ranges(COMBINING, cp) then return 0 end
  return 1
end

--- 解码位置 i 处的 UTF-8 序列
--- @param s string
--- @param i number 1-based 字节位置
--- @return number|nil 码点；非法字节返回 nil
--- @return number 字节长度（非法字节固定为 1）
local function _decode(s, i)
  local b1 = s:byte(i)
  if not b1 then return nil, 0 end
  if b1 < 0x80 then return b1, 1 end
  if b1 >= 0xC2 and b1 <= 0xDF then
    local b2 = s:byte(i + 1)
    if b2 and b2 >= 0x80 and b2 <= 0xBF then
      return (b1 - 0xC0) * 64 + (b2 - 0x80), 2
    end
  elseif b1 >= 0xE0 and b1 <= 0xEF then
    local b2, b3 = s:byte(i + 1), s:byte(i + 2)
    if b2 and b3 and b2 >= 0x80 and b2 <= 0xBF and b3 >= 0x80 and b3 <= 0xBF
      and not (b1 == 0xE0 and b2 < 0xA0) and not (b1 == 0xED and b2 > 0x9F) then
      return (b1 - 0xE0) * 4096 + (b2 - 0x80) * 64 + (b3 - 0x80), 3
    end
  elseif b1 >= 0xF0 and b1 <= 0xF4 then
    local b2, b3, b4 = s:byte(i + 1), s:byte(i + 2), s:byte(i + 3)
    if b2 and b3 and b4 and b2 >= 0x80 and b2 <= 0xBF and b3 >= 0x80 and b3 <= 0xBF
      and b4 >= 0x80 and b4 <= 0xBF
      and not (b1 == 0xF0 and b2 < 0x90) and not (b1 == 0xF4 and b2 > 0x8F) then
      return (b1 - 0xF0) * 262144 + (b2 - 0x80) * 4096 + (b3 - 0x80) * 64 + (b4 - 0x80), 4
    end
  end
  return nil, 1
end

-- ========== 公开 API ==========

--- 字符串显示宽度（等价 vim.fn.strwidth）
--- @param s string|nil
--- @return number
function M.strwidth(s)
  if s == nil or s == "" then return 0 end
  -- 纯 ASCII（无高位字节）快速路径：显示宽度 == 字节数
  if not s:find("[\128-\255]") then return #s end
  local i, n, w = 1, #s, 0
  while i <= n do
    local cp, len = _decode(s, i)
    w = w + ((cp == nil) and 4 or _width(cp))
    i = i + len
  end
  return w
end

--- 码点个数（等价 vim.fn.strchars，非法字节计 1）
--- @param s string|nil
--- @return number
function M.strchars(s)
  if s == nil or s == "" then return 0 end
  -- 纯 ASCII 快速路径：字符数 == 字节数
  if not s:find("[\128-\255]") then return #s end
  local i, n, c = 1, #s, 0
  while i <= n do
    local _, len = _decode(s, i)
    c = c + 1
    i = i + len
  end
  return c
end

--- 按码点切片（等价 vim.fn.strcharpart）
--- @param s string|nil
--- @param start number 0-based 码点起始
--- @param len number|nil 码点长度（nil = 到末尾；<=0 = 空串）
--- @return string
function M.strcharpart(s, start, len)
  if s == nil or s == "" then return "" end
  start = start or 0
  -- 负 start：对齐 vim（start 归零，同时按 |start| 削减 len）
  if start < 0 then
    if len ~= nil then len = len + start end
    start = 0
  end
  if len ~= nil and len <= 0 then return "" end
  local n = #s
  local i, idx = 1, 0
  while idx < start and i <= n do
    local _, l = _decode(s, i)
    i = i + l
    idx = idx + 1
  end
  if i > n then return "" end
  local from = i
  if len == nil then return s:sub(from) end
  local cnt = 0
  while cnt < len and i <= n do
    local _, l = _decode(s, i)
    i = i + l
    cnt = cnt + 1
  end
  return s:sub(from, i - 1)
end

--- 按 "\n" 切分为行数组（等价 vim.split(text, "\n", { plain = true })）
--- @param text string|nil
--- @return table 行数组（空串返回 { "" }）
function M.split_lines(text)
  text = text or ""
  local out = {}
  local start = 1
  while true do
    local nl = text:find("\n", start, true)
    if nl then
      out[#out + 1] = text:sub(start, nl - 1)
      start = nl + 1
    else
      out[#out + 1] = text:sub(start)
      return out
    end
  end
end

--- 遍历码点：返回 (char, width)；非法字节作为单字符、宽度按 vim 计 4。
--- 单遍扫描，供折行等需要逐字符宽度的场景使用（避免 O(n²) 的逐字符切片）。
--- @param s string|nil
--- @return function 迭代器
function M.each_char(s)
  local i, n = 1, #(s or "")
  local str = s or ""
  return function()
    if i > n then return nil end
    local cp, len = _decode(str, i)
    local ch = str:sub(i, i + len - 1)
    i = i + len
    return ch, (cp == nil) and 4 or _width(cp)
  end
end

-- ========== 工作线程源码 ==========
-- 本模块纯 Lua（不 require / 不引用 vim.*），可把 M.source 传入 utils.work 线程内
-- `load(source)()` 得到同一实现。source 在模块加载时从自身文件读取（只读一次）。

--- 读取本模块源码（供工作线程 load 使用）；失败返回 nil，调用方应回退同步路径。
--- @return string|nil
local function _read_own_source()
  local info = debug.getinfo(1, "S")
  local src = info and info.source
  if type(src) ~= "string" or src:sub(1, 1) ~= "@" then return nil end
  local f = io.open(src:sub(2), "rb")
  if not f then return nil end
  local content = f:read("*a")
  f:close()
  return content
end

M.source = _read_own_source()

return M
